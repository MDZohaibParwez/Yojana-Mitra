const { chromium, devices } = require('playwright');
const BASE = process.env.BASE_URL || 'http://localhost:3000';
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['Pixel 5'], locale: 'hi-IN' });
  const p = await ctx.newPage();
  const errors = [];
  p.on('pageerror', e => errors.push(e.message));
  await p.goto(BASE + '/');
  await p.selectOption('#state', 'GJ'); await p.fill('#age', '42'); await p.selectOption('#gender', 'male');
  await p.selectOption('#occupation', 'farmer'); await p.fill('#annualIncome', '150000'); await p.fill('#landAcres', '3');
  await p.click('main form button[type=submit]');
  await p.waitForSelector('#results h2', { timeout: 15000 });
  console.log('results:', await p.textContent('#results h2'));
  await p.screenshot({ path: (process.env.SHOT_DIR || '.') + '/home.png' });
  await p.locator('#results h3').first().scrollIntoViewIfNeeded();
  await p.screenshot({ path: (process.env.SHOT_DIR || '.') + '/results.png' });
  await p.goto(BASE + '/chat');
  await p.locator('main input').fill('main 35 saal ki vidhwa mahila hoon, UP ke gaon mein, BPL card hai');
  await p.locator('main form button').click();
  await p.waitForTimeout(3000);
  console.log('chat:', (await p.locator('main').innerText()).slice(0, 200).replace(/\n/g, ' | '));
  await p.screenshot({ path: (process.env.SHOT_DIR || '.') + '/chat.png' });
  await p.goto(BASE + '/s?ids=pm-kisan,pm-jay');
  console.log('shared cards:', await p.locator('h3').count());
  await p.goto(BASE + '/scheme/pm-kisan');
  console.log('detail h1:', await p.textContent('h1'));
  console.log('notice on page:', await p.locator('[role=note]').count());
  console.log('errors', errors);
  await b.close();
})();
